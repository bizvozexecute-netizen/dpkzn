/**
 * Иконки дизайн-системы — инлайновый SVG (ДС §3, «иконки — inline SVG stroke»).
 *
 * Замена lucide-react: пакет добавлял отдельный чанк к каждой странице ради
 * полутора десятков глифов, а стиль всё равно один — обводка 1.75, currentColor.
 * Здесь ровно те иконки, что используются, и ни одной лишней.
 */

interface IconProps {
  size?: number;
  className?: string;
}

function Svg({ size = 20, className, children }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      {children}
    </svg>
  );
}

